#!/usr/bin/env python3

import argparse
import hashlib
import pathlib
import sys
from datetime import datetime
from zoneinfo import ZoneInfo


ROOT = pathlib.Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "ATLAS_PROJECT_CONTEXT.md"
LOCAL_TZ = ZoneInfo("America/Los_Angeles")

SOURCES = [
    ROOT / "ATLAS_NEXT.md",
    ROOT / "ATLAS_BLOCKERS.md",
    ROOT / "ATLAS_DECISIONS.md",
    ROOT / "ATLAS_WORKFLOW.md",
    ROOT / "ATLAS_FEATURES_PLAIN_LANGUAGE.md",
    ROOT / "ATLAS_SFSU_ACCESS_CHECKLIST.md",
    ROOT / "SFSU_EMAIL_BENEFITS.md",
    ROOT / "ATLAS_SFSU_SERVER_BRIDGE_PLAN.md",
    ROOT / "homelab-codex-handoff-latest.md",
    ROOT / "homelab-change-log.md",
]


def read(path: pathlib.Path) -> str:
    return path.read_text(encoding="utf-8")


def section(text: str, heading: str, level: int = 2) -> str:
    prefix = "#" * level + " "
    target = prefix + heading
    lines = text.splitlines()
    start = None
    for index, line in enumerate(lines):
        if line.strip() == target:
            start = index
            break
    if start is None:
        return f"{target}\n\n_Not found in source._"
    end = len(lines)
    for index in range(start + 1, len(lines)):
        line = lines[index]
        if line.startswith(prefix) and not line.startswith(prefix + "#"):
            end = index
            break
    return "\n".join(lines[start:end]).strip()


def first_change(text: str) -> str:
    lines = text.splitlines()
    starts = [index for index, line in enumerate(lines) if line.startswith("## ")]
    if not starts:
        return "## Latest change\n\n_No change entry found._"
    start = starts[0]
    end = starts[1] if len(starts) > 1 else len(lines)
    return "\n".join(lines[start:end]).strip()


def digest(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def generated_time() -> str:
    newest = max(path.stat().st_mtime for path in SOURCES)
    return datetime.fromtimestamp(newest, LOCAL_TZ).isoformat(timespec="seconds")


def build() -> str:
    missing = [str(path) for path in SOURCES if not path.exists()]
    if missing:
        raise FileNotFoundError("missing context sources: " + ", ".join(missing))

    next_text = read(ROOT / "ATLAS_NEXT.md")
    blockers = read(ROOT / "ATLAS_BLOCKERS.md")
    decisions = read(ROOT / "ATLAS_DECISIONS.md")
    workflow = read(ROOT / "ATLAS_WORKFLOW.md")
    features = read(ROOT / "ATLAS_FEATURES_PLAIN_LANGUAGE.md")
    sfsu = read(ROOT / "SFSU_EMAIL_BENEFITS.md")
    handoff = read(ROOT / "homelab-codex-handoff-latest.md")
    changes = read(ROOT / "homelab-change-log.md")

    source_rows = "\n".join(
        f"| `{path.name}` | `{digest(path)}` |"
        for path in SOURCES
    )

    content = f"""# ATLAS Project Context

> Generated automatically by `tools/ai/build-atlas-project-context.py`
> Source snapshot time: {generated_time()}
> Do not edit this file directly; update its source documents and regenerate it.

## How to use this file

This is the first-read briefing for future ATLAS work. Follow the Current item unless the user explicitly reprioritizes it or a recovery issue takes precedence. Status words are evidence levels, not informal descriptions.

{section(workflow, "Status model")}

{section(workflow, "Definition of done")}

## Active work queue

{next_text.split('>', 1)[-1].strip()}

## Blocker snapshot

{section(blockers, "Open blockers")}

## Current user-visible capability snapshot

{section(features, "At a glance")}

## School-data privacy decision

{section(sfsu, "Permanent decision")}

## Deployed/current technical decisions

{section(handoff, "Current Decisions")}

## Privacy boundary

{section(handoff, "Privacy Boundary")}

## Latest material change

{first_change(changes)}

## Accepted decision index

{chr(10).join(line for line in decisions.splitlines() if line.startswith('## DEC-'))}

Read `ATLAS_DECISIONS.md` before changing one of these accepted choices.

## Task-specific follow-up

Open only the source relevant to the active task. For SFSU authorization details,
use `ATLAS_SFSU_ACCESS_CHECKLIST.md`; for bridge design, use
`ATLAS_SFSU_SERVER_BRIDGE_PLAN.md`. Historical and generated material is not
default session context.

## Session close requirement

Use `ATLAS_SESSION_HANDOFF_TEMPLATE.md`, update the appropriate source documents, and regenerate this file. A locally tested feature remains `locally_verified` until deployed and proven through the real user path.

## Source fingerprints

| Source | SHA-256 prefix |
|---|---|
{source_rows}
"""
    return content.rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Build or verify the compact ATLAS project context.")
    parser.add_argument("--check", action="store_true", help="Exit nonzero when the generated context is missing or stale.")
    args = parser.parse_args()

    expected = build()
    if args.check:
        if not OUTPUT.exists():
            print(f"stale: {OUTPUT} does not exist", file=sys.stderr)
            raise SystemExit(1)
        if read(OUTPUT) != expected:
            print(f"stale: regenerate {OUTPUT} with {pathlib.Path(__file__).name}", file=sys.stderr)
            raise SystemExit(1)
        print("ATLAS project context is current")
        return

    OUTPUT.write_text(expected, encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
